-- 微盘/特处保持不可调度（研究档案）
UPDATE "行情增量"."数据集登记" SET
  "可调度" = FALSE,
  "备注" = COALESCE("备注", '') || CASE
    WHEN COALESCE("备注", '') LIKE '%研究档案%' THEN ''
    ELSE '；研究档案，人工/冻结，不接自动调度'
  END
WHERE "数据源" IN ('微盘股研究', '特别处理研究')
  AND "可调度" IS DISTINCT FROM FALSE;
