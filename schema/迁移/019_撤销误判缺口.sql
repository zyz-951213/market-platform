-- 019:撤销"误判为已修复"的缺口(判据缺陷:当天有行 ≠ 已补齐)
--
-- 背景(2026-10-06):
--   缺口回填原来的复判条件是"区间内每个应有交易日**是否存在行**"。
--   个股资金流向的缺口日里有几天只有 **5 行**(旧即时口径写入的残留),
--   于是这 11 条缺口被误置为 `已修复` —— 实际远未补齐(参照日约 5200 行/日)。
--
--   代码已改为**覆盖度判据**:同区间内每日行数 ≥ 最大日行数 × 0.5 才算补齐
--   (见 `data/存储/缺口回填.py::_区间已补齐`)。本迁移把误判的条目改回 `待处理`。
--
-- 幂等:可重复执行(第二次已无 `已修复` 且备注含该标记的行)。

UPDATE 行情增量.缺口登记
   SET 状态 = '待处理',
       备注 = COALESCE(备注, '') ||
               ' | 2026-10-06 更正:此前按"当天有行即补齐"误判为已修复,实为残缺日(每日仅个位数行,参照约 5200 行)',
       更新时间 = now()
 WHERE 数据集 = '个股资金流向'
   AND 状态 = '已修复'
   AND 备注 NOT LIKE '%2026-10-06 更正%';
