-- 020:再次撤销误判的缺口(补齐判据改为"数据集 p90 日行数 × 25%")
--
-- 判据演进(两次踩坑,记录以免后人重犯):
--   ① 只看"当天有没有行"        → 个股资金流向的残缺日(5 行/日)被当成已补齐;
--   ② 参照取"被检查区间内最大值" → 整段都是残缺日的区间**内部自证完整**(区间内最大只有 5 ⇒ 门槛退化);
--   ③ 参照取"近 180 天中位数"    → 该表大多数日子本身就是残缺的(中位 57 行 vs 完整日 5213 行);
--   ④ 现行:参照取**近 365 天日行数的 p90**,门槛 = p90 × 25%,且数据集本身很小(<10 行/日)时不设门槛。
--
-- 本迁移把 个股资金流向 被 ①②③ 误置为 `已修复` 的条目改回 `待处理`。
-- 该数据集的实际状态:接口有 120 天逐股历史,已取回 2394 行,源限流中断,可续跑。
--
-- 幂等:可重复执行。

UPDATE 行情增量.缺口登记
   SET 状态 = '待处理',
       备注 = COALESCE(备注, '') ||
               ' | 2026-10-06 再次更正:补齐判据已改为"数据集 p90 日行数 × 25%",'
               '本区间每日仅个位数~57 行(完整日约 5213 行),远未补齐,不能置为已修复',
       更新时间 = now()
 WHERE 数据集 = '个股资金流向'
   AND 状态 = '已修复'
   AND 备注 NOT LIKE '%再次更正%';

-- 自证:不该再有"个股资金流向 已修复"
DO $$
DECLARE n bigint;
BEGIN
  SELECT count(*) INTO n FROM 行情增量.缺口登记
   WHERE 数据集 = '个股资金流向' AND 状态 = '已修复';
  IF n > 0 THEN
    RAISE EXCEPTION '个股资金流向 仍有 %.0f 条被标为已修复,判据未生效', n;
  END IF;
END $$;
