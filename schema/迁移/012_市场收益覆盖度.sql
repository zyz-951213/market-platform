-- 012:市场收益文件 增加覆盖度标记(防止用残缺样本算出的收益被当权威)
--
-- 背景:2026-07-24 之后 `公共.个股日行情文件` 的股票覆盖率从约 5600 只/日塌陷到 1260 只/日
-- (8、9 月部分恢复),导致按 公共.日行情 聚合出的"计算段"在那些日期上样本残缺,
-- 与档案段**不可直接比较**。此前的构建器不会察觉这一点,会把残缺样本的结果当正常值写库。
--
-- 本迁移:补 `覆盖度`(当日总家数 / 参照家数)与 `覆盖完整` 两列;
-- 构建器据此打标并在日志里告警,消费方可按 `覆盖完整` 过滤。

ALTER TABLE 公共.市场收益文件
  ADD COLUMN IF NOT EXISTS 覆盖度 numeric(6,4),
  ADD COLUMN IF NOT EXISTS 覆盖完整 boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN 公共.市场收益文件.覆盖度 IS
  '当日总家数 / 参照家数(档案段最后 20 个交易日的日均总家数);仅计算段有意义';
COMMENT ON COLUMN 公共.市场收益文件.覆盖完整 IS
  '覆盖度是否 ≥ 阈值(默认 0.90);false 表示该日样本残缺,数值不可与档案段直接比较';

-- 档案段视为完整(其家数即当时的真实覆盖)
UPDATE 公共.市场收益文件 SET 覆盖完整 = true WHERE 数据段 = '档案';
