-- 010:市场类型编码字典 + 市场收益两段口径(档案/计算)
--
-- 背景(TASK-004):
--   · `公共.市场收益文件` 用 smallint 编码表示市场分段(1/2/4/8/16/32/64),但**全仓没有任何文档**
--     解释这些编码;`公共.市场收益` 视图直接读它,却只有档案段(≤2026-05-20),
--     增量段没有任何写入者 ⇒ 视图在分界日之后是空的。
--   · 编码含义已用**两条独立证据**反推并坐实:
--       ① 起始日对齐已知开市日(1990-12-19 上交所 / 1991-01-04 深交所 / 1992-02-21 沪B /
--          1992-02-28 深B / 2009-10-30 创业板 / 2019-07-22 科创板 / 2020-07-27 精选层);
--       ② 按 公共.日行情 聚合出的**成交量与家数与档案逐一对上**
--          (2026-05-20:编码1=1697家、4=1486、16=1395、32=608、64=312、2=41、8=37,
--           成交量完全一致;等权收益率差 ≤5bp,差异来自复权口径)。
--
-- 本迁移:
--   1) 建 `公共.市场类型字典` 并写入编码含义(含依据与口径说明);
--   2) 给 `公共.市场收益文件` 增加 `数据段` 列('档案' / '计算'),既有行标为 '档案';
--   3) 把 `日市场回报率文件` 在登记表里标为不可调度(其旧写入器写的是指数行,已由新构建器取代),
--      并把 `市场收益文件` 登记为可调度(入口 = 数据底座.市场收益构建)。
--
-- 幂等:可重复执行。

-- ── 1) 编码字典 ─────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS 公共.市场类型字典 (
  编码      smallint PRIMARY KEY,
  名称      text NOT NULL,
  证券代码前缀 text[] NOT NULL DEFAULT '{}',   -- 构建增量时据此归类
  依据      text,
  备注      text
);

COMMENT ON TABLE 公共.市场类型字典 IS
  '公共.市场收益文件.market_type 的编码含义(2026-10-06 反推坐实,依据见各行"依据"列)';

INSERT INTO 公共.市场类型字典 (编码, 名称, 证券代码前缀, 依据, 备注) VALUES
  (1,  '沪市A股(主板)', ARRAY['60'],           '起始日 1990-12-19 = 上交所开业日',            '成交量/家数与 公共.日行情 聚合完全一致'),
  (2,  '沪市B股',       ARRAY['900'],          '起始日 1992-02-21 = 上海B股开市日',           '家数约 41,与 B 股规模一致'),
  (4,  '深市A股(主板)', ARRAY['00'],           '起始日 1991-01-04 = 深交所开始交易日',        '成交量/家数与 公共.日行情 聚合一一致'),
  (8,  '深市B股',       ARRAY['200'],          '起始日 1992-02-28 = 深圳B股开市日',           '家数约 37'),
  (16, '创业板',        ARRAY['30'],           '起始日 2009-10-30 = 创业板开市日',            ''),
  (32, '科创板',        ARRAY['68'],           '起始日 2019-07-22 = 科创板开市日',            ''),
  (64, '北交所(含精选层)', ARRAY['8','4','920'], '起始日 2020-07-27 = 新三板精选层设立日',    '代码前缀跨 43xxxx/83xxxx/87xxxx/920xxx')
ON CONFLICT (编码) DO UPDATE
  SET 名称 = EXCLUDED.名称,
      证券代码前缀 = EXCLUDED.证券代码前缀,
      依据 = EXCLUDED.依据,
      备注 = EXCLUDED.备注;

COMMENT ON COLUMN 公共.市场收益文件.market_type IS
  '市场分段编码,含义见 公共.市场类型字典(1=沪A 2=沪B 4=深A 8=深B 16=创业板 32=科创板 64=北交所)';

-- ── 2) 数据段标记 ───────────────────────────────────────────────────────
ALTER TABLE 公共.市场收益文件
  ADD COLUMN IF NOT EXISTS 数据段 text NOT NULL DEFAULT '档案';

COMMENT ON COLUMN 公共.市场收益文件.数据段 IS
  '档案 = CSMAR 档案段(≤ 日行情.档案分界日);计算 = 由 公共.日行情 按同口径聚合(增量段)';

UPDATE 公共.市场收益文件 SET 数据段 = '档案' WHERE 数据段 IS NULL;

-- ── 3) 登记表:口径与调度归属 ─────────────────────────────────────────────
INSERT INTO 行情增量.数据集登记
  (数据源, 数据集, 对象类型, 水位列, 责任方, 更新策略, 更新入口, 可调度, 备注)
VALUES
  ('公共', '市场收益文件', '表', 'trade_date', 'database', '增量',
   '数据底座.市场收益构建', true,
   '档案段(CSMAR)∪ 计算段(由 公共.日行情 聚合,口径实测一致:家数/成交量完全一致,等权收益差≤5bp)')
ON CONFLICT (数据源, 数据集) DO UPDATE
  SET 水位列 = EXCLUDED.水位列,
      责任方 = EXCLUDED.责任方,
      更新策略 = EXCLUDED.更新策略,
      更新入口 = EXCLUDED.更新入口,
      可调度 = EXCLUDED.可调度,
      备注 = EXCLUDED.备注;

UPDATE 行情增量.数据集登记
   SET 可调度 = false,
       备注 = COALESCE(NULLIF(备注, ''), '') ||
               CASE WHEN COALESCE(备注, '') = '' THEN '' ELSE ' | ' END ||
               '已改由 市场收益文件(数据底座.市场收益构建)承载;本表保留为原始抓取记录,不再调度'
 WHERE 数据源 = '公共' AND 数据集 = '日市场回报率文件';
