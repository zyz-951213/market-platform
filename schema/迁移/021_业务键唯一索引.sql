-- 021:为"缺业务键唯一索引"的可调度表补索引(纯列键)
--
-- 背景(2026-10-06 审计):17 张可调度表没有业务键唯一索引,`_insert` 只能
-- `ON CONFLICT DO NOTHING` —— 没有约束可冲突,重跑即整行再插
-- (实测龙虎榜营业部 1810 行完全重复,见迁移 017)。
--
-- 选键原则(不用脚本猜键):
--   · 只用**语义标识列**(代码/日期/期次/类型/名称),不含金额、占比、涨幅等**度量列** ——
--     否则"同样的记录被重新抓取、数值被修正"会变成插新行,幂等失效;
--   · 键必须**无 NULL 且当前唯一**(NULL 会让唯一索引失效,PostgreSQL 视 NULL 互不相等);
--   · 只建**纯列索引**:`_insert` 的键发现(`pg_attribute.attnum` 关联)不认识表达式索引,
--     会解析出残缺列名并导致 ON CONFLICT 报错后**静默跳过写入**,比不建更糟。
--
-- 幂等:CREATE UNIQUE INDEX IF NOT EXISTS。

-- ── 月度/季度宏观表:期次 + 数据标识 ────────────────────────────────────
CREATE UNIQUE INDEX IF NOT EXISTS uq_采购经理人指数表_月度
  ON 公共."采购经理人指数表" ("月度");

CREATE UNIQUE INDEX IF NOT EXISTS uq_固定资产投资表_月度
  ON 公共."固定资产投资表(月)" ("月度");

CREATE UNIQUE INDEX IF NOT EXISTS uq_工业生产者出厂价格_月度_标识
  ON 公共."工业生产者出厂价格涨幅表(月)" ("月度", "数据标识");

CREATE UNIQUE INDEX IF NOT EXISTS uq_规模以上工业增加值_月度_标识
  ON 公共."规模以上工业增加值增速表(月)" ("月度", "数据标识");

CREATE UNIQUE INDEX IF NOT EXISTS uq_居民消费价格_月度_标识
  ON 公共."居民消费价格涨幅表(月)" ("月度", "数据标识");

CREATE UNIQUE INDEX IF NOT EXISTS uq_社会消费品零售_月度_标识
  ON 公共."社会消费品零售总额表(月)" ("月度", "数据标识");

CREATE UNIQUE INDEX IF NOT EXISTS uq_各层次货币供应量_月度标识
  ON 公共."各层次货币供应量月度文件" ("月度标识");

-- ── 日频/事件型 ─────────────────────────────────────────────────────────
CREATE UNIQUE INDEX IF NOT EXISTS uq_汇率文件_汇率日期
  ON 公共."汇率文件" ("汇率日期");

CREATE UNIQUE INDEX IF NOT EXISTS uq_央行公开市场业务_日期_业务
  ON 公共."央行公开市场业务" ("日期标识", "业务名称");

CREATE UNIQUE INDEX IF NOT EXISTS uq_公司文件_证券代码
  ON 公共."公司文件" ("证券代码");

CREATE UNIQUE INDEX IF NOT EXISTS uq_上市状态变更_代码_公布日
  ON 公共."上市状态变更表" ("证券代码", "变动公布日期");

CREATE UNIQUE INDEX IF NOT EXISTS uq_国内生产总值_季度_更新日期
  ON 公共."国内生产总值表(季)" ("季度", "更新日期");

COMMENT ON INDEX 公共.uq_上市状态变更_代码_公布日 IS
  '业务键:同一标的同一公布日的状态变更只应有一条(2026-10-06 补,防重跑重复写入)';

-- ── 未建索引的表与原因(需业务确认,不做猜测式去重)──────────────────────
-- 公共.分配文件        : 同一 (证券代码, 除权(息)日期) 有 9286 组"内容不同"的行
--                        (例:002410 2013-06-06 两行分别为 分配比率 0.5 / 0.3,后者把转增比
--                         误填进分配比率) ⇒ 需先定"哪一版为准",不是索引能解决的;
-- 公共.龙虎榜营业部     : 23025 组同键不同内容 —— 机构席位快照行(上榜原因为 NULL)把多个
--                        "上榜原因口径的聚合"挤进同一键,表结构缺判别列 ⇒ 需schema/业务确认;
-- 公共.龙虎榜          : 12 组为同一 (日期,代码,原因) 的重复抓取版本(金额略有差异);
-- 公共.人民币存款准备金率表: 同日多条调整记录(如 2008-06-07),缺判别列;
-- 公共.指数基本信息文件 : 两个来源(akshare / 补充)对同代码给出不同的开始日期与基准点数。
--
-- 以上 5 张表由 `market-platform data 数据体检` 的『业务键唯一性』项持续报告。
