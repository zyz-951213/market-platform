-- 005:修正公共层业务键 —— 指数日行情补「指数中文简称」维度
--
-- 背景(TASK-003 D2):
--   迁移 001 显式跳过了 国内指数日行情文件 与 日市场回报率文件,理由是"仍有业务键重复"。
--   体检后发现两张表的性质完全不同:
--
--   (1) 公共.国内指数日行情文件 —— **键少了一维**:
--       同一个「交易所指数代码」会对应多个指数,例如 980001 同时是
--       "湾创100" 与 "中华半导体芯片全收益"。因此按 (交易所指数代码, 交易日期)
--       分组必然出现 3472 组"重复",这不是脏数据,而是键定义不全。
--       实测:按 (交易所指数代码, 指数中文简称, 交易日期) 分组 → 0 组重复。
--       ⇒ 本迁移**只加唯一索引,不删任何数据**。
--
--   (2) 公共.日市场回报率文件 —— **确有脏数据**:
--       按 (市场类型, 交易日期) 有 8707 组、共 41345 行重复,且各组内**取值不同**
--       (同一日期同一市场类型有多套股数/金额)。这属于"多套数据被并进同一张表",
--       保留规则需要业务判断,**本迁移不动它**,只在下面留档并在注册表里标注。
--
-- 幂等:全部 CREATE ... IF NOT EXISTS,可重复执行。

-- ── (1) 指数日行情:补全业务键后加唯一索引 ────────────────────────────────
-- 先做一次防御性校验:若仍有重复,索引创建会失败并中止整个迁移(宁可失败也不静默)。
DO $$
DECLARE
  dup_groups integer;
BEGIN
  SELECT count(*) INTO dup_groups FROM (
    SELECT "交易所指数代码", "指数中文简称", "交易日期"
    FROM "公共"."国内指数日行情文件"
    GROUP BY 1, 2, 3 HAVING count(*) > 1
  ) t;
  IF dup_groups > 0 THEN
    RAISE EXCEPTION '国内指数日行情文件 在三列业务键上仍有 % 组重复,请先人工核对', dup_groups;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS 国内指数日行情文件_代码_简称_日期_uidx
  ON 公共.国内指数日行情文件 ("交易所指数代码", "指数中文简称", "交易日期");

COMMENT ON INDEX 公共.国内指数日行情文件_代码_简称_日期_uidx IS
  '业务键:(交易所指数代码, 指数中文简称, 交易日期)。缺"简称"维会把不同指数混为一谈(如 980001)。';

-- ── (2) 日市场回报率文件:登记待清洗(不改数据)─────────────────────────────
DO $$
DECLARE
  dup_groups integer;
  dup_rows integer;
BEGIN
  SELECT count(*), COALESCE(sum(n), 0) INTO dup_groups, dup_rows FROM (
    SELECT "市场类型", "交易日期", count(*) AS n
    FROM "公共"."日市场回报率文件"
    GROUP BY 1, 2 HAVING count(*) > 1
  ) t;
  RAISE NOTICE '日市场回报率文件: (市场类型,交易日期) 重复 % 组 / % 行 —— 组内取值不同,需业务判断后再清洗,本次不动数据',
    dup_groups, dup_rows;
END $$;
