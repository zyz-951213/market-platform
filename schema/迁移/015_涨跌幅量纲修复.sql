-- 015:修复 `个股日行情文件.涨跌幅` 量纲错误(百分数 vs 小数)
--
-- 背景(2026-10-06 查实):
--   库内 `个股日行情文件.涨跌幅`(= `公共.日行情.pct_chg`,经 日行情_增量 视图)
--   混了两种量纲:
--     · source='akshare'  2026-05-21 → 2026-07-24  257418 行:小数(如 -0.0288)
--     · source='baostock' 2026-07-27 → 2026-09-30  240822 行:百分数(如 -2.88)  ✗
--   原因是 baostock 的 pctChg 字段单位是百分数,写入时未换算
--   (`数据更新器_baostock.py: "涨跌幅": _to_n(r[11])`),而 CSMAR 档案段是小数。
--   后果:等权/流通市值/总市值加权的日收益率被放大 100 倍
--   (2026-08-05 计算段等权收益曾算出 110%),任何按该列做的研究结论都会失真。
--   判据:按日统计 avg(abs(涨跌幅)),异常日 ≈ 2.4–3.3(百分数),正常日 ≈ 0.02–0.04(小数)。
--
-- 本迁移:
--   1) 对 source='baostock' 的行做 涨跌幅 = 涨跌幅 / 100(其写入语义恒为百分数);
--   2) 建 `<表>_涨跌幅量纲修复备份_<日期>` 快照表,便于回滚;
--   3) 写入侧已同步修复(新增 `_pct_to_ratio()`),防止复发。
--
-- 幂等:重复执行不会二次除以 100 —— 第二次执行时 source='baostock' 且
--       avg(abs(涨跌幅)) < 0.15,条件 `abs(涨跌幅) > 0.15` 不再命中。

-- 备份(仅第一次执行时建立,已存在则跳过)
CREATE TABLE IF NOT EXISTS 公共."个股日行情文件_涨跌幅量纲修复备份_20261006" AS
SELECT * FROM 公共."个股日行情文件" WHERE false;

INSERT INTO 公共."个股日行情文件_涨跌幅量纲修复备份_20261006"
SELECT * FROM 公共."个股日行情文件"
WHERE source = 'baostock' AND "涨跌幅" IS NOT NULL AND abs("涨跌幅") > 0.15
  AND NOT EXISTS (
    SELECT 1 FROM 公共."个股日行情文件_涨跌幅量纲修复备份_20261006" b
    WHERE b."序号" = 公共."个股日行情文件"."序号"
  );

-- 修复:百分数 → 小数
UPDATE 公共."个股日行情文件"
   SET "涨跌幅" = "涨跌幅" / 100.0
 WHERE source = 'baostock'
   AND "涨跌幅" IS NOT NULL
   AND abs("涨跌幅") > 0.15;

COMMENT ON TABLE 公共."个股日行情文件" IS
  'CSMAR 个股日行情原始表。涨跌幅口径 = 小数(如 -0.0288);'
  '2026-10-06 曾修复 source=baostock 的 240462 行百分数量纲(见 schema/迁移/015)';
