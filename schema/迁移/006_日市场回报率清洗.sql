-- 006:日市场回报率文件 —— 归位错标行 + 去重 + 加业务键唯一约束
--
-- 背景(TASK-003 D2b,体检结论):
--   该表曾被写入器 bug 污染:
--     · `数据更新器_补充.update_market_daily` 把 上证综指/深证成指/创业板指 三个指数的行
--       **全部标成 市场类型='A股'**,同一天因此出现多行同名记录;
--     · 幂等检查只按 `交易日期` 单键,且在循环中不更新已存在集合 ⇒ 重复被放大。
--   (写入器已在代码侧修复:改按指数命名市场类型 + 复合幂等键 + 集合同步。)
--
--   本迁移只做**可证明**的清理,顺序如下:
--     1) 全表备份到 公共.日市场回报率文件_清洗备份_20261006;
--     2) 把 'A股' 行按「成交量唯一匹配某个指数」归位到正确市场类型
--        (实测 137/137 行都能唯一匹配,故这不是猜测);
--     3) 对剩余重复组按「非空字段最多 → 序号最小」保留一行,其余删除;
--     4) 建业务键唯一索引 (交易日期, 市场类型),使此后写入在数据库层就幂等。
--
--   注:本表**当前没有任何代码读取者**(`公共.市场收益` 视图读的是另一张 `市场收益文件`),
--   因此清理风险低;且第 1 步已留全量备份,可随时回退:
--     INSERT INTO 公共.日市场回报率文件 SELECT * FROM 公共.日市场回报率文件_清洗备份_20261006;
--
-- 幂等:重复执行时,备份表 IF NOT EXISTS 不再重建,后续步骤在有唯一索引后自然为空操作。

-- ── 1) 全量备份 ──────────────────────────────────────────────────────────
DO $$
BEGIN
  IF to_regclass('公共.日市场回报率文件_清洗备份_20261006') IS NULL THEN
    EXECUTE 'CREATE TABLE 公共.日市场回报率文件_清洗备份_20261006 AS
             SELECT * FROM 公共.日市场回报率文件';
    RAISE NOTICE '已备份 公共.日市场回报率文件 → 公共.日市场回报率文件_清洗备份_20261006';
  ELSE
    RAISE NOTICE '备份表已存在,跳过备份';
  END IF;
END $$;

-- ── 2) 归位错标的 'A股' 行(仅当成交量唯一匹配一个指数) ────────────────────
DO $$
DECLARE
  更新数 integer;
BEGIN
  WITH 候选 AS (
    SELECT m.序号, i."指数中文简称" AS 名称
    FROM 公共.日市场回报率文件 m
    JOIN 公共.国内指数日行情文件 i
      ON i."交易日期" = m."交易日期"
     AND i."成份证券成交量" IS NOT NULL
     AND abs(i."成份证券成交量" - m."日市场交易总股数") < 0.5
    WHERE m."市场类型" = 'A股'
      AND i."指数中文简称" IN ('上证综指', '深证成指', '创业板指')
  ), 唯一 AS (
    SELECT 序号, min(名称) AS 名称 FROM 候选 GROUP BY 序号 HAVING count(*) = 1
  )
  UPDATE 公共.日市场回报率文件 m
     SET "市场类型" = 唯一.名称,
         updated_at = now()
    FROM 唯一
   WHERE m.序号 = 唯一.序号;
  GET DIAGNOSTICS 更新数 = ROW_COUNT;
  RAISE NOTICE '按成交量唯一匹配,归位错标行 % 条(剩余未匹配的 A股 行保留原样)', 更新数;
END $$;

-- ── 3) 去重:每组保留「非空字段最多 → 序号最小」的一行 ─────────────────────
DO $$
DECLARE
  删前 integer;
  删后 integer;
  删除数 integer;
BEGIN
  SELECT count(*) INTO 删前 FROM 公共.日市场回报率文件;
  WITH 排序 AS (
    SELECT "序号",
           row_number() OVER (
             PARTITION BY "交易日期", "市场类型"
             ORDER BY (
               (CASE WHEN "日市场交易总股数" IS NULL THEN 0 ELSE 1 END) +
               (CASE WHEN "日市场交易总金额" IS NULL THEN 0 ELSE 1 END) +
               (CASE WHEN "考虑现金红利再投资的日市场回报率(等权平均" IS NULL THEN 0 ELSE 1 END) +
               (CASE WHEN "考虑现金红利再投资的日市场回报率(流通市值" IS NULL THEN 0 ELSE 1 END) +
               (CASE WHEN "考虑现金红利再投资的日市场回报率(总市值加" IS NULL THEN 0 ELSE 1 END)
             ) DESC,
             "序号" ASC
           ) AS rn
    FROM 公共.日市场回报率文件
  )
  DELETE FROM 公共.日市场回报率文件 t
   USING 排序 s
   WHERE t."序号" = s."序号" AND s.rn > 1;
  GET DIAGNOSTICS 删除数 = ROW_COUNT;
  SELECT count(*) INTO 删后 FROM 公共.日市场回报率文件;
  RAISE NOTICE '去重: % → % 行(删除 % 行,保留规则=非空字段最多→序号最小;备份在 清洗备份_20261006)',
    删前, 删后, 删除数;
END $$;

-- ── 4) 业务键唯一索引(此后写入在数据库层幂等)─────────────────────────────
CREATE UNIQUE INDEX IF NOT EXISTS 日市场回报率文件_交易日期_市场类型_uidx
  ON 公共.日市场回报率文件 ("交易日期", "市场类型");

COMMENT ON INDEX 公共.日市场回报率文件_交易日期_市场类型_uidx IS
  '业务键:(交易日期, 市场类型)。市场类型现为指数简称(上证综指/深证成指/创业板指),此前曾被错标为 ''A股''。';

-- ── 5) 登记表备注(口径与历史问题留痕)────────────────────────────────────
UPDATE 行情增量.数据集登记
   SET 备注 = COALESCE(备注 || ' | ', '') ||
              '键曾因写入器 bug 不可分辨(2026-10-06 已清洗并加唯一约束);仅含 3 指数等权口径'
 WHERE 数据源 = '公共' AND 数据集 = '日市场回报率文件';
