-- 014:深市B股代码前缀补全 + `市场收益文件.权重口径` 披露列
--
-- 背景1(深B 少数一只,2026-10-06 查实):
--   `公共.市场类型字典` 原写 深市B股 前缀 = {200};但 CSMAR 深B 市场**同时包含 201xxx**
--   (如 201872,2018-12-26 起在 公共.日行情 中有 1931 行)。只认 200xxx 会使
--   深B 少数一只 ⇒ 2026-05-20 计算家数 36 vs 档案 37、成交量不一致。
--   补上 201 后:家数 37/37、成交量一致,流通/总市值加权差 ≤1.1bp。
--
-- 背景2(市值加权缺口):
--   2026-07-27 起 `公共.日行情` 增量段的 `mkt_cap`/`float_mkt_cap` 全为 NULL
--   (抓取器不算市值),导致计算段的 ret_float_vw/ret_total_vw 在 286 行上为 NULL。
--   构建器改为**回退到"最近已知股本 × 当日收盘价"**重建权重,并在此列公开口径,
--   使消费方能区分"当日市值口径"与"股本结转口径"。
--
-- 幂等:可重复执行。


-- ── 1) 深B 前缀补全 ─────────────────────────────────────────────────────
UPDATE 公共.市场类型字典
   SET 证券代码前缀 = ARRAY['200', '201'],
       备注 = '家数约 37;201xxx(如 201872)亦属深B,只认 200xxx 会少数一只'
 WHERE 编码 = 8;

-- ── 2) 权重口径披露列 ───────────────────────────────────────────────────
ALTER TABLE 公共.市场收益文件
  ADD COLUMN IF NOT EXISTS 权重口径 text;

COMMENT ON COLUMN 公共.市场收益文件.权重口径 IS
  '流通/总市值加权的权重来源:当日市值 = 用前一交易日 日行情 市值列;'
  '股本结转 = 当日市值列缺失,回退到"最近已知股本 × 当日收盘价"(仅计算段可能出现);'
  'NULL = 档案段(权重口径即 CSMAR 原始定义)';

-- 档案段权重口径由 CSMAR 定义,不适用本列语义
UPDATE 公共.市场收益文件 SET 权重口径 = NULL WHERE 数据段 = '档案';

