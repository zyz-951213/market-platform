/**
 * 统一站点数据源定义 —— 三个域在此登记,站点壳与网关共用同一份元数据。
 *
 * 约定(生产):子应用页面在 `/<域>/`,接口在 `/<域>/api/*`,由统一网关
 * (`market_platform.门户.应用`)同时托管静态产物与三条 API 分支。
 * 约定(开发):子应用各自跑自己的 dev server,站点壳按 dev 地址内嵌。
 */

export interface 域信息 {
  /** 域名称,同时作为站点路径前缀与接口前缀 */
  名: string;
  /** 一句话职责说明 */
  说明: string;
  /** 接口端口(独立运行时的真实端口,也是网关内部转发目标) */
  端口: number;
  /** 开发模式下子应用 dev server 地址 */
  开发地址: string;
  /** 主题色 */
  色: string;
}

