/** 取某域在指定模式下的页面地址 */
export function 域页面地址(域: 域信息, 开发模式: boolean): string {
  return 开发模式 ? 域.开发地址 : `/${域.名}/`;
}

/** 取某域接口基址(与各子应用内 VITE_API_BASE 保持一致) */
export function 域接口基址(域: 域信息, 开发模式: boolean): string {
  return 开发模式 ? 域.开发地址.replace(/\/$/, "") : `/${域.名}/api`;
}
