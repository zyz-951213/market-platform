_CSRC_RE = re.compile(r"^([A-Z]\d{2})(.+)$")


def to_citic_l1(sector: str) -> str:
    text = str(sector or "").strip()
    if not text or text == "未分类":
        return "综合"
    return SHENWAN_TO_CITIC_L1.get(text, text)


def to_citic_l2(csrc_l2: str, *, citic_l1: str = "") -> str:
    text = str(csrc_l2 or "").strip()
    if not text or text == "未分类":
        return citic_l1 or "综合"
    if text in CSRC_L2_TO_CITIC_L2:
        return CSRC_L2_TO_CITIC_L2[text]
    match = _CSRC_RE.match(text)
    if match:
        text = match.group(2).strip()
        if text in CSRC_L2_TO_CITIC_L2:
            return CSRC_L2_TO_CITIC_L2[text]
    for suffix in ("业", "制造业", "服务业"):
        if text.endswith(suffix) and len(text) > len(suffix) + 1:
            short = text[: -len(suffix)]
            if short in CSRC_L2_TO_CITIC_L2.values():
                return short
    return text[:12] if len(text) > 12 else text


def apply_citic_labels(df: pd.DataFrame) -> pd.DataFrame:
    """将 hierarchy 列转为中信一级/二级行业名。"""
    if df.empty:
        return df
    out = df.copy()
    out["symbol"] = out["symbol"].astype(str).str.zfill(6)
    sw_l1 = out["sector_l1"].astype(str) if "sector_l1" in out.columns else pd.Series(["未分类"] * len(out))
    csrc_l2 = out["sector_l2"].astype(str) if "sector_l2" in out.columns else sw_l1
    out["sector_l1"] = sw_l1.map(to_citic_l1)
    out["sector_l2"] = [
        to_citic_l2(l2, citic_l1=l1) for l1, l2 in zip(out["sector_l1"], csrc_l2, strict=True)
    ]
    if "sector" in out.columns:
        out["sector"] = out["sector_l1"]
    return out.drop_duplicates("symbol").sort_values(["sector_l1", "sector_l2", "name", "symbol"])
